from typing import Protocol, Callable
from .models import ClaimedJob, LeaseRef, WorkerResult, WorkerStatus, FactPack, Locale, ProviderReceipt


class BrokerClientProtocol(Protocol):
    async def claim(self, model_ready: bool) -> ClaimedJob | None: ...
    async def heartbeat(self, lease: LeaseRef | None, model_ready: bool) -> WorkerStatus: ...
    async def complete(self, result: WorkerResult) -> None: ...
    async def close(self) -> None: ...


class ChronicleProvider(Protocol):
    async def readiness(self) -> bool: ...
    async def generate(self, pack: FactPack, locale: Locale, reserve: Callable[[int], None]) -> ProviderReceipt: ...
    async def close(self) -> None: ...
