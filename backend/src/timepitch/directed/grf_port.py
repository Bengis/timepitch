"""Injected directed ABI only. No loader, factory, entry point or admission."""
from typing import Protocol


class GrfDirectedPort(Protocol):
    def capabilities(self) -> dict: ...
    def prepare(self, initial: dict) -> dict: ...
    def queue(self, command: dict) -> dict: ...
    def step(self, ticks: int) -> dict: ...
    def export(self) -> dict: ...
    def close(self) -> None: ...
