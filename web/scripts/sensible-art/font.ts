/** Ancho de avance de cada carácter tras engordar (5 → 6 columnas + 1 de sombra + 1 de separación). */
export const ADVANCE = 8;

/**
 * Pinta `text` en un búfer de índices: relleno con degradado vertical (fill arriba, shade en las 2 filas de abajo),
 * trazo engordado 1 px a la derecha y contorno/sombra de 1 px con `outline`.
 */
export function drawText(text: string, fill: number, shade: number, outline: number) {
  const w = text.length * ADVANCE + 2, h = 7 + 3, idx = new Uint8Array(w * h);
  [...text.toUpperCase()].forEach((ch, n) => {
    const g = GLYPHS[ch] ?? GLYPHS[' '];
    g.forEach((row, y) => [...row].forEach((c, x) => {
      if (c !== '#') return;
      for (const dx of [0, 1]) idx[(y + 1) * w + 1 + n * ADVANCE + x + dx] = y >= 5 ? shade : fill;
    }));
  });
  const src = idx.slice();
  for (let y = 0; y < h; y++) for (let x = 0; x < w; x++) {
    if (src[y * w + x]) continue;
    const s = (xx: number, yy: number) => xx >= 0 && yy >= 0 && xx < w && yy < h && src[yy * w + xx] !== 0;
    if (s(x - 1, y) || s(x + 1, y) || s(x, y - 1) || s(x, y + 1) || s(x - 1, y - 1)) idx[y * w + x] = outline;
  }
  return { w, h, idx };
}
