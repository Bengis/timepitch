import { useId, useState } from 'react';
import { createPortal } from 'react-dom';
import statsbombIcon from '../assets/statsbomb.svg?no-inline';
import { useLanguage } from '../i18n';
import { defineTexts } from '../i18n-catalog';
import type { AttributionLine } from './attribution';
import './tokens.css';
import './credits.css';

const LICENCE_URLS: Readonly<Record<string, string>> = {
  'CC BY-SA 4.0': 'https://creativecommons.org/licenses/by-sa/4.0/',
  'CC BY-SA 3.0': 'https://creativecommons.org/licenses/by-sa/3.0/',
  CC0: 'https://creativecommons.org/publicdomain/zero/1.0/',
  MIT: '/licenses/three.txt',
  'AGPL-3.0-or-later': 'https://www.gnu.org/licenses/agpl-3.0.html',
  'Apache-2.0 / The Unlicense': 'https://www.apache.org/licenses/LICENSE-2.0',
};

// TP221: rótulos del panel en inglés y español; las líneas llegan ya traducidas desde `attributionsFor`.
const TEXTS = defineTexts('credits', {
  en: { title: 'Credits and licences', close: 'Close',
    // TP234: nota de inspiración y originalidad de Capitán Hane (nombrar la inspiración es atribución, no uso).
    // TP235: los primeros planos de la demo son de FLUX.2-pro (solo rasgos del avatar, revisados uno a uno).
    inspirationTitle: 'Inspiration and originality',
    inspiration: 'Captain Hane is inspired by 1980s–90s sports anime and the Tecmo Captain Tsubasa games. Move names, sounds, lettering and scene graphics are original and generated by TimePitch code. The close-up portraits of the demo players are AI-generated with FLUX.2-pro on Azure AI Foundry, prompted only with each avatar’s traits (no names or photos), and every image was reviewed; other players get code-drawn portraits.' },
  es: { title: 'Créditos y licencias', close: 'Cerrar',
    inspirationTitle: 'Inspiración y originalidad',
    inspiration: 'Capitán Hane está inspirado en el anime deportivo de los años 80 y 90 y en los juegos de Captain Tsubasa de Tecmo. Los nombres de los movimientos, los sonidos, la rotulación y los gráficos de la escena son originales y los genera el código de TimePitch. Los primeros planos de los jugadores de la demo están generados con IA (FLUX.2-pro en Azure AI Foundry) solo a partir de los rasgos de su avatar (sin nombres ni fotos), y cada imagen se revisó; el resto de jugadores lleva retratos dibujados por código.' },
});

/** Pie con enlace «Créditos y licencias» y diálogo con las líneas de `attributionsFor`. */
export function CreditsPanel({ lines }: { lines: readonly AttributionLine[] }) {
  const [open, setOpen] = useState(false);
  const titleId = useId();
  const t = TEXTS(useLanguage().locale);
  return (
    <footer className="tp-credits">
      <button type="button" className="tp-credits-link" onClick={() => setOpen(true)}>{t.title}</button>
      {/* Portal a <body>: `.unified-centre` usa container-type y contendría el `position: fixed` del fondo. */}
      {open && createPortal(
        <div className="tp-credits-backdrop" onClick={(e) => { if (e.target === e.currentTarget) setOpen(false); }}>
          <div role="dialog" aria-modal="true" aria-labelledby={titleId} className="tp-credits-dialog"
            onKeyDown={(e) => { if (e.key === 'Escape') setOpen(false); }}>
            <h2 id={titleId}>{t.title}</h2>
            <ul>
              {lines.map((l) => {
                const licenceUrl = LICENCE_URLS[l.licence];
                return (
                  <li key={l.id} data-attribution={l.id}>
                    {l.id === 'statsbomb' && <img src={statsbombIcon} alt="Hudl Statsbomb" width="24" height="24" />}
                    <span className="tp-credits-text">
                      {l.url ? <a href={l.url} target="_blank" rel="noreferrer">{l.text}</a> : <span>{l.text}</span>}
                      {' · '}
                      {licenceUrl
                        ? <a className="tp-credits-licence" href={licenceUrl} target="_blank" rel="noreferrer">{l.licence}</a>
                        : <span className="tp-credits-licence">{l.licence}</span>}
                    </span>
                  </li>
                );
              })}
            </ul>
            <section className="tp-credits-inspiration" data-anime-inspiration>
              <h3>{t.inspirationTitle}</h3><p>{t.inspiration}</p>
            </section>
            <button type="button" className="tp-credits-close" autoFocus onClick={() => setOpen(false)}>{t.close}</button>
          </div>
        </div>,
        document.body,
      )}
    </footer>
  );
}
