import { fireEvent, render, screen, within } from '@testing-library/react';
import { afterEach, expect, it } from 'vitest';
import { LanguageProvider, type Locale } from '../i18n';
import { CreditsPanel } from './CreditsPanel';
import type { AttributionLine } from './attribution';

const LINES: AttributionLine[] = [
  { id: 'statsbomb', text: 'Datos de eventos: StatsBomb Open Data (Hudl).', licence: 'StatsBomb Open Data', url: 'https://github.com/hudl/open-data' },
  { id: 'wikipedia:A:1', text: 'Equipación: artículo «A» (revisión 1).', licence: 'CC BY-SA 4.0', url: 'https://en.wikipedia.org/w/index.php?title=A&oldid=1' },
  { id: 'own-art', text: 'Arte propio.', licence: 'TimePitch', url: null },
];

function renderIn(locale: Locale) {
  localStorage.setItem('timepitch.locale', locale);
  return render(<LanguageProvider><CreditsPanel lines={LINES} /></LanguageProvider>);
}
afterEach(() => localStorage.removeItem('timepitch.locale'));

it('shows a footer link and opens a dialog with every line, licence links and the StatsBomb logo', () => {
  renderIn('es');
  expect(screen.queryByRole('dialog')).toBeNull();
  fireEvent.click(screen.getByRole('button', { name: 'Créditos y licencias' }));
  const dialog = screen.getByRole('dialog', { name: 'Créditos y licencias' });
  expect(within(dialog).getAllByRole('listitem')).toHaveLength(3);
  expect(within(dialog).getByRole('link', { name: /StatsBomb Open Data \(Hudl\)/ })).toHaveAttribute('href', 'https://github.com/hudl/open-data');
  expect(within(dialog).getByRole('img', { name: 'Hudl Statsbomb' })).toBeInTheDocument();
  expect(within(dialog).getByRole('link', { name: 'CC BY-SA 4.0' })).toHaveAttribute('href', 'https://creativecommons.org/licenses/by-sa/4.0/');
  expect(within(dialog).getByText('Arte propio.').closest('a')).toBeNull();
});

it('closes with the close button, with Escape and by clicking the backdrop', () => {
  renderIn('es');
  const open = screen.getByRole('button', { name: 'Créditos y licencias' });
  fireEvent.click(open);
  fireEvent.click(screen.getByRole('button', { name: 'Cerrar' }));
  expect(screen.queryByRole('dialog')).toBeNull();
  fireEvent.click(open);
  fireEvent.keyDown(screen.getByRole('dialog'), { key: 'Escape' });
  expect(screen.queryByRole('dialog')).toBeNull();
  fireEvent.click(open);
  fireEvent.click(screen.getByRole('dialog'));
  expect(screen.getByRole('dialog')).toBeInTheDocument();
  fireEvent.click(document.querySelector('.tp-credits-backdrop')!);
  expect(screen.queryByRole('dialog')).toBeNull();
});

it('labels the link, dialog and close button in English when the UI is in English', () => {
  renderIn('en');
  expect(screen.queryByRole('button', { name: 'Créditos y licencias' })).toBeNull();
  fireEvent.click(screen.getByRole('button', { name: 'Credits and licences' }));
  const dialog = screen.getByRole('dialog', { name: 'Credits and licences' });
  expect(within(dialog).getAllByRole('listitem')).toHaveLength(3);
  fireEvent.click(within(dialog).getByRole('button', { name: 'Close' }));
  expect(screen.queryByRole('dialog')).toBeNull();
});

// TP234: the Captain Hane inspiration and originality note, in both languages.
it.each([
  ['en', 'Credits and licences', 'Inspiration and originality', 'inspired by 1980s–90s sports anime and the Tecmo Captain Tsubasa games. Move names, sounds, lettering and scene graphics are original and generated by TimePitch code. The close-up portraits of the demo players are AI-generated with FLUX.2-pro on Azure AI Foundry, prompted only with each avatar’s traits (no names or photos), and every image was reviewed; other players get code-drawn portraits.'],
  ['es', 'Créditos y licencias', 'Inspiración y originalidad', 'Los nombres de los movimientos, los sonidos, la rotulación y los gráficos de la escena son originales y los genera el código de TimePitch. Los primeros planos de los jugadores de la demo están generados con IA (FLUX.2-pro en Azure AI Foundry) solo a partir de los rasgos de su avatar (sin nombres ni fotos), y cada imagen se revisó; el resto de jugadores lleva retratos dibujados por código.'],
] as const)('the credits carry the anime inspiration note (%s)', (locale, button, title, text) => {
  renderIn(locale);
  fireEvent.click(screen.getByRole('button', { name: button }));
  const note = screen.getByRole('dialog').querySelector('[data-anime-inspiration]')!;
  expect(within(note as HTMLElement).getByRole('heading', { name: title })).toBeInTheDocument();
  expect(note.textContent).toContain(text);
});
