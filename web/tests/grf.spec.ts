test('engine selector defaults to TimePitch and preserves TimePitch selections and tactics',async({page})=>{
  await page.goto('/');await page.getByRole('button',{name:'More details'}).click();
  const selector=page.getByRole('combobox',{name:'Simulation engine',exact:true});
  const capabilities=await (await page.request.get('/api/engines')).json();
  await expect(selector).toHaveValue('timepitch');
  await selector.selectOption('timepitch');
  const home=page.getByRole('article',{name:'Home team',exact:true});
  await expect(home.getByRole('heading',{name:'Arsenal',exact:true})).toBeVisible();
  await home.getByRole('combobox',{name:'Tactic',exact:true}).selectOption('press');
  if(capabilities.find((v:{id:string})=>v.id==='grf')?.available){
    await expect(selector.locator('option[value="grf"]')).toHaveJSProperty('disabled',false);
    await selector.selectOption('grf');
    await expect(home.getByRole('combobox',{name:'Tactic',exact:true})).toBeDisabled();
    await expect(home.locator('.season-tag')).toHaveText('2003/04');
    await selector.selectOption('timepitch');
    await expect(home.getByRole('combobox',{name:'Tactic',exact:true})).toHaveValue('press');
  }else await expect(selector.locator('option[value="grf"]')).toHaveJSProperty('disabled',true);
});

test('missing GRF assets disable the option and explain the reason in both languages',async({page})=>{
  await page.route('**/api/engines',route=>route.fulfill({json:[{id:'timepitch',available:true},{id:'grf',available:false,reason:'missing_assets'}]}));
  await page.goto('/');await page.getByRole('button',{name:'More details'}).click();
  const selector=page.getByRole('combobox',{name:'Simulation engine',exact:true});
  await expect(selector).toHaveValue('timepitch');
  await expect(selector.locator('option[value="grf"]')).toHaveJSProperty('disabled',true);
  await expect(page.locator('.engine-selector')).toContainText('Required GRF files are missing');
  await page.getByRole('button', { name: 'Language: Español' }).click();
  await expect(page.locator('.engine-selector')).toContainText('Faltan archivos necesarios de GRF');
});

